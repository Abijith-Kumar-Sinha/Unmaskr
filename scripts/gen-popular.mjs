// Build the popularity gate: a Bloom filter of the Tranco top-N registrable domains.
//   node scripts/gen-popular.mjs [N=100000] [fpRate=0.001]  -> src/data/popular.ts
// The hash must match src/algorithms/popular.ts (FNV-1a, double hashing).
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const N = Number(process.argv[2] ?? 100000)
const P = Number(process.argv[3] ?? 0.001)
const rows = readFileSync(resolve(ROOT, 'data-eval/raw/top-1m.csv'), 'utf8').split(/\r?\n/).filter(Boolean)
const domains = rows.slice(0, N).map((r) => r.split(',')[1].trim().toLowerCase())

const m = Math.ceil((-domains.length * Math.log(P)) / Math.LN2 ** 2)
const k = Math.max(1, Math.round((m / domains.length) * Math.LN2))
function fnv(s, seed) {
  let h = seed >>> 0
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0 }
  return h >>> 0
}
const bits = new Uint8Array(Math.ceil(m / 8))
for (const d of domains) {
  const h1 = fnv(d, 2166136261), h2 = fnv(d, 0x9747b28c) | 1
  for (let i = 0; i < k; i++) { const b = (h1 + Math.imul(i, h2)) >>> 0; const j = b % m; bits[j >> 3] |= 1 << (j & 7) }
}
const b64 = Buffer.from(bits).toString('base64')
writeFileSync(resolve(ROOT, 'src/data/popular.ts'), `// AUTO-GENERATED by scripts/gen-popular.mjs — do not edit.
// Bloom filter of the Tranco top ${N} registrable domains (list of ${rows.length > 0 ? 'Jun 13, 2026' : ''}),
// false-positive rate ${P}: m = ${m} bits, k = ${k} hashes, ${(b64.length / 1024).toFixed(0)} KB.
export const POPULAR = { n: ${domains.length}, m: ${m}, k: ${k}, bits: '${b64}' } as const
`)
console.log(`popular.ts: n=${domains.length} m=${m} k=${k} ${(b64.length / 1024).toFixed(0)} KB`)
