// Build the popularity gate: the EXACT sorted list of the Tranco top-N domains.
//   node scripts/gen-popular.mjs [N=100000]   -> src/data/popular.ts
// Exact on purpose: a probabilistic filter (Bloom) ships its false positives to the
// attacker, who can search for a lookalike name it wrongly calls "popular".
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const N = Number(process.argv[2] ?? 100000)
const rows = readFileSync(resolve(ROOT, 'data-eval/raw/top-1m.csv'), 'utf8').split(/\r?\n/).filter(Boolean)
const domains = [...new Set(rows.slice(0, N).map((r) => r.split(',')[1].trim().toLowerCase()))]
  .filter((d) => /^[a-z0-9.-]+$/.test(d))
  .sort() // UTF-16 code-unit order, matched by the binary search in src/algorithms/popular.ts
const text = domains.join('\n')
writeFileSync(resolve(ROOT, 'src/data/popular.ts'), `// AUTO-GENERATED by scripts/gen-popular.mjs — do not edit.
// The Tranco top ${N} domains (list of Jun 13, 2026), sorted, newline-separated:
// ${domains.length} entries, ${(text.length / 1024).toFixed(0)} KB.
export const POPULAR_SORTED = '${text.replace(/\n/g, '\\n')}'
`)
console.log(`popular.ts: ${domains.length} domains, ${(text.length / 1024).toFixed(0)} KB`)
